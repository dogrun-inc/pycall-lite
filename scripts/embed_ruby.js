import fs from "node:fs";
import path from "node:path";

const pycallRbPath = path.resolve("lib/pycall.rb");
const importRbPath = path.resolve("lib/pycall/import.rb");
const outputPath = path.resolve("src/ruby_code.ts");

const pycallRb = fs.readFileSync(pycallRbPath, "utf-8");
const importRb = fs.readFileSync(importRbPath, "utf-8");

// Ensure src directory exists
if (!fs.existsSync(path.dirname(outputPath))) {
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
}

const content = `// This file is auto-generated by scripts/embed_ruby.js. Do not edit directly.
export const pycallRb = ${JSON.stringify(pycallRb)};
export const importRb = ${JSON.stringify(importRb)};
`;

fs.writeFileSync(outputPath, content, "utf-8");
console.log("Embedded Ruby source files into src/ruby_code.ts successfully.");
